    private void populateProductTable(List<Product> products) {
        DefaultTableModel model = (DefaultTableModel) tblProducts.getModel();
        model.setRowCount(0);
        for (Product p : products) {
            model.addRow(new Object[]{
                    p.getProductId(),
                    p.getProductName(),
                    p.getSize(),
                    p.getColor(),
                    String.format("$%.2f", p.getPrice()),
                    p.getQuantity()
            });
        }
    }

    // ── Load customers into cmbCustomer ───────────────────────────────
    private void loadCustomers() {
        cmbCustomer.removeAllItems();
        cmbCustomer.addItem("-- Walk-in Customer --");
        List<Customer> customers = customerDAO.getAllCustomers();
        for (Customer c : customers) {
            cmbCustomer.addItem(c);
        }
    }

    private void setupCustomerSearch() {
        btnSearchCustomer.addActionListener(e -> {
            String keyword = txtCustomerSearch.getText().trim();
            if (keyword.isEmpty()) {
                loadCustomers(); // reset to show all
                return;
            }

            // Search customers by name or phone
            List<Customer> results = customerDAO.searchCustomer(keyword);
            cmbCustomer.removeAllItems();
            cmbCustomer.addItem("-- Walk-in Customer --");

            if (results.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "No customer found with: " + keyword,
                        "Not Found", JOptionPane.INFORMATION_MESSAGE);
            } else {
                for (Customer c : results) {
                    cmbCustomer.addItem(c);
                }
                // Auto-select if only one result found
                if (results.size() == 1) {
                    cmbCustomer.setSelectedIndex(1);
                }
            }
        });

        // Press Enter in search field = same as clicking Find
        txtCustomerSearch.addActionListener(e -> btnSearchCustomer.doClick());
    }

